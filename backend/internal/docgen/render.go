// RenderPDF produces a watermarked one-page PDF for a synthetic document.
func RenderPDF(d *model.Document, u *model.User, issuerName string) []byte {
	p := newPage()
	status := d.EffectiveStatus(time.Now())

	// Sandbox band
	p.Rect(0, 812, 595, 30, 0.80, 0.16, 0.16)
	p.Text(24, 822, "F2", 10, 1, 1, 1, "MOCK DIGILOCKER SANDBOX  •  SYNTHETIC TEST DATA  •  NOT A GOVERNMENT DOCUMENT")

	// Header
	p.Rect(24, 730, 547, 70, 0.95, 0.96, 0.98)
	p.Text(40, 776, "F1", 10, 0.35, 0.38, 0.45, issuerName)
	p.Text(40, 752, "F2", 20, 0.10, 0.14, 0.25, d.Description)
	p.Text(40, 737, "F1", 9, 0.35, 0.38, 0.45, "Issued via Mock DigiLocker • URI: "+d.URI)

	// Document number
	p.Text(40, 700, "F1", 9, 0.40, 0.42, 0.48, "DOCUMENT NUMBER")
	p.Text(40, 680, "F2", 18, 0.10, 0.14, 0.25, d.DocNumber)

	// Fields
	y := 640.0
	p.Line(40, y+14, 555, y+14, 0.6, 0.85, 0.86, 0.9)
	for _, fl := range catalog.FieldLabels(d.DocType) {
		v := d.Fields[fl[0]]
		if v == "" {
			continue
		}
		if fl[0] == "dob" {
			v = FormatDOB(v, "02-01-2006")
		}
		if fl[0] == "gender" {
			v = GenderLabel(v)
		}
		p.Text(40, y, "F1", 9, 0.40, 0.42, 0.48, strings.ToUpper(fl[1]))
		for i, line := range wrap(v, 62) {
			p.Text(200, y-float64(i)*14, "F2", 11, 0.10, 0.12, 0.18, line)
			if i > 0 {
				y -= 14
			}
		}
		y -= 26
	}
	y -= 6
	p.Line(40, y+14, 555, y+14, 0.6, 0.85, 0.86, 0.9)
	rows := [][2]string{{"ISSUE DATE", FormatDOB(d.IssueDate, "02-01-2006")}}
	if d.ValidFrom != "" {
		rows = append(rows, [2]string{"VALID FROM", FormatDOB(d.ValidFrom, "02-01-2006")})
	}
	if d.ValidTo != "" {
		rows = append(rows, [2]string{"VALID UPTO", FormatDOB(d.ValidTo, "02-01-2006")})
	}
	rows = append(rows, [2]string{"VERIFICATION STATUS", strings.ToUpper(status)}, [2]string{"DIGILOCKER ID", u.ID})
	for _, r := range rows {
		p.Text(40, y, "F1", 9, 0.40, 0.42, 0.48, r[0])
		p.Text(200, y, "F2", 11, 0.10, 0.12, 0.18, r[1])
		y -= 24
	}

	// Status stamp
	if status != model.DocValid {
		label := strings.ToUpper(status)
		p.StrokeRect(380, 668, 175, 46, 3, 0.80, 0.10, 0.10)
		p.Text(380+(175-TextWidth(label, 24, true))/2, 683, "F2", 24, 0.80, 0.10, 0.10, label)
	}

	// Watermarks
	for _, yy := range []float64{150, 400, 650} {
		p.RotText(48, yy, 28, "F2", 21, 0.75, 0.05, 0.05, Watermark)
	}

	// Footer
	p.Rect(24, 40, 547, 52, 1.0, 0.95, 0.93)
	p.Text(36, 74, "F2", 10, 0.70, 0.12, 0.12, Watermark)
	p.Text(36, 60, "F1", 8, 0.35, 0.30, 0.30, "This document was generated from a synthetic test persona by an open-source DigiLocker-compatible sandbox.")
	p.Text(36, 49, "F1", 8, 0.35, 0.30, 0.30, "It is not issued by any government authority and has no legal validity. Generated "+time.Now().UTC().Format(time.RFC3339))
	return p.Render(d.Description + " (DEMO)")
}

func wrap(s string, n int) []string {
	words := strings.Fields(s)
	var lines []string
	cur := ""
	for _, w := range words {
		if len(cur)+len(w)+1 > n && cur != "" {
			lines = append(lines, cur)
			cur = w
		} else if cur == "" {
			cur = w
		} else {
			cur += " " + w
		}
	}
	if cur != "" {
		lines = append(lines, cur)
	}
	if len(lines) == 0 {
		lines = []string{""}
	}
	return lines
}

// FormatDOB converts YYYY-MM-DD into the requested Go layout.
func FormatDOB(iso, layout string) string {
	t, err := time.Parse("2006-01-02", iso)
	if err != nil {
		return iso
	}
	return t.Format(layout)
}

func GenderLabel(g string) string {
	switch g {
	case "M":
		return "Male"
	case "F":
		return "Female"
	case "T":
		return "Transgender"
	}
	return g
}

func x(s string) string {
	var b bytes.Buffer
	_ = xml.EscapeText(&b, []byte(s))
	return strings.ReplaceAll(b.String(), `"`, "&#34;")
}

// statusCode maps statuses to the single-letter certificate status codes.
func statusCode(s string) string {
	switch s {
	case model.DocValid:
		return "A"
	case model.DocExpired:
		return "E"
	case model.DocRevoked:
		return "R"
	case model.DocInvalid:
		return "I"
	}
	return "U"
}

// RenderXML produces DigiLocker-style certificate XML for an issued document.
func RenderXML(d *model.Document, u *model.User, issuerName string) []byte {
	status := d.EffectiveStatus(time.Now())
	ddmmyyyy := func(iso string) string { return FormatDOB(iso, "02-01-2006") }
	a := u.Address
	var b strings.Builder
	b.WriteString(`<?xml version="1.0" encoding="UTF-8" standalone="yes"?>` + "\n")
	b.WriteString("<!-- " + Watermark + ". Generated by Mock DigiLocker sandbox from synthetic data. -->\n")
	fmt.Fprintf(&b, `<Certificate language="99" name="%s" type="%s" number="%s" prevNumber="" expiryDate="%s" validFromDate="%s" issuedAt="Sandbox" issueDate="%s" status="%s" demo="true">`+"\n",
		x(d.Description), x(d.DocType), x(d.DocNumber), x(ddmmyyyy(d.ValidTo)), x(ddmmyyyy(d.ValidFrom)), x(ddmmyyyy(d.IssueDate)), statusCode(status))
	fmt.Fprintf(&b, `  <IssuedBy><Organization name="%s" code="%s" tin="" uid="" type="CG"><Address type="" line1="Sandbox Bhawan" line2="" house="" landmark="" locality="" vtc="Mockpur" district="Mockpur" pin="000000" state="Sandbox" country="IN"/></Organization></IssuedBy>`+"\n",
		x(issuerName), x(d.OrgID))
	fmt.Fprintf(&b, `  <IssuedTo><Person uid="%s" title="" name="%s" dob="%s" swd="%s" swdIndicator="" motherName="" gender="%s" maritalStatus="" relationWithHead="" disabilityStatus="" category="" religion="" phone="%s" email="%s">`+"\n",
		x(maskedUID(u)), x(u.Name), x(ddmmyyyy(u.DOB)), x(u.FatherName), x(u.Gender), x(u.Mobile), x(u.Email))
	fmt.Fprintf(&b, `    <Address type="permanent" line1="%s" line2="%s" house="%s" landmark="%s" locality="%s" vtc="%s" district="%s" pin="%s" state="%s" country="IN"/>`+"\n",
		x(a.House), x(a.Street), x(a.House), x(a.Landmark), x(a.Locality), x(a.VTC), x(a.District), x(a.Pincode), x(a.State))
	fmt.Fprintf(&b, `    <Photo format="jpeg">%s</Photo>`+"\n", PlaceholderPhotoBase64())
	b.WriteString("  </Person></IssuedTo>\n  <CertificateData>\n")
	switch d.DocType {
	case catalog.DocPAN:
		fmt.Fprintf(&b, `    <PAN number="%s" name="%s" fatherName="%s" dob="%s" status="%s"/>`+"\n", x(d.DocNumber), x(u.Name), x(u.FatherName), x(ddmmyyyy(u.DOB)), statusCode(status))
	case catalog.DocDL:
		fmt.Fprintf(&b, `    <DrivingLicense number="%s" issueDate="%s" expiryDate="%s" issuingAuthority="%s" bloodGroup="%s">`+"\n", x(d.DocNumber), x(ddmmyyyy(d.IssueDate)), x(ddmmyyyy(d.ValidTo)), x(d.Fields["rto"]), x(d.Fields["blood_group"]))
		b.WriteString(`      <Categories><Category abbreviation="LMV" description="Light Motor Vehicle" issueDate="` + x(ddmmyyyy(d.IssueDate)) + `"/><Category abbreviation="MCWG" description="Motor Cycle With Gear" issueDate="` + x(ddmmyyyy(d.IssueDate)) + `"/></Categories>` + "\n")
		b.WriteString("    </DrivingLicense>\n")
	case catalog.DocRC:
		fmt.Fprintf(&b, `    <VehicleRegistration registrationNumber="%s" owner="%s" makerModel="%s" fuel="%s" chassisNumber="%s" registrationDate="%s" validUpto="%s"/>`+"\n",
			x(d.DocNumber), x(d.Fields["owner"]), x(d.Fields["maker_model"]), x(d.Fields["fuel"]), x(d.Fields["chassis_no"]), x(ddmmyyyy(d.IssueDate)), x(ddmmyyyy(d.ValidTo)))
	case catalog.DocAadhaar:
		fmt.Fprintf(&b, `    <Aadhaar maskedNumber="%s" name="%s" dob="%s" gender="%s"/>`+"\n", x(d.Fields["masked_aadhaar"]), x(u.Name), x(ddmmyyyy(u.DOB)), x(u.Gender))
	}
	fmt.Fprintf(&b, "    <Remarks>%s</Remarks>\n", x(Watermark))
	b.WriteString("  </CertificateData>\n")
	b.WriteString(`  <Signature xmlns="http://www.w3.org/2000/09/xmldsig#"><SignedInfo><SignatureMethod Algorithm="urn:mock-digilocker:unsigned"/></SignedInfo><SignatureValue>MOCK-SANDBOX-NOT-SIGNED</SignatureValue></Signature>` + "\n")
	b.WriteString("</Certificate>\n")
	return []byte(b.String())
}

func maskedUID(u *model.User) string {
	if u.AadhaarLast4 == "" {
		return ""
	}
	return "xxxxxxxx" + u.AadhaarLast4
}

// RenderEAadhaarXML mimics the e-Aadhaar (KYC) XML returned by
// /oauth2/3/xml/eaadhaar, populated with synthetic data.
func RenderEAadhaarXML(u *model.User) []byte {
	a := u.Address
	ts := time.Now().Format("2006-01-02T15:04:05.000-07:00")
	var b strings.Builder
	b.WriteString(`<?xml version="1.0" encoding="UTF-8" standalone="yes"?>` + "\n")
	b.WriteString("<!-- " + Watermark + ". Synthetic e-Aadhaar data from Mock DigiLocker sandbox. -->\n")
	b.WriteString(`<Certificate language="99" name="Aadhaar Card" type="ADHAR" demo="true">` + "\n  <CertificateData>\n")
	fmt.Fprintf(&b, `    <KycRes code="MOCK%s" ret="Y" ts="%s" ttl="%s" txn="UKC:MOCK:%s">`+"\n", strings.ToUpper(u.ID[:8]), ts, time.Now().AddDate(1, 0, 0).Format("2006-01-02T15:04:05"), u.ID[:8])
	fmt.Fprintf(&b, `      <UidData tkn="" uid="%s">`+"\n", x(maskedUID(u)))
	fmt.Fprintf(&b, `        <Poi dob="%s" gender="%s" name="%s"/>`+"\n", x(FormatDOB(u.DOB, "02-01-2006")), x(u.Gender), x(u.Name))
	fmt.Fprintf(&b, `        <Poa co="%s" country="India" dist="%s" house="%s" lm="%s" loc="%s" pc="%s" po="%s" state="%s" street="%s" subdist="%s" vtc="%s"/>`+"\n",
		x(a.CareOf), x(a.District), x(a.House), x(a.Landmark), x(a.Locality), x(a.Pincode), x(a.VTC), x(a.State), x(a.Street), x(a.SubDistrict), x(a.VTC))
	b.WriteString("        <LData/>\n")
	fmt.Fprintf(&b, "        <Pht>%s</Pht>\n", PlaceholderPhotoBase64())
	b.WriteString("      </UidData>\n    </KycRes>\n  </CertificateData>\n")
	b.WriteString(`  <Signature xmlns="http://www.w3.org/2000/09/xmldsig#"><SignatureValue>MOCK-SANDBOX-NOT-SIGNED</SignatureValue></Signature>` + "\n</Certificate>\n")
	return []byte(b.String())
}

var (
	placeholderPhoto string
	photoOnce        sync.Once
)

// PlaceholderPhotoBase64 returns a small grey silhouette JPEG (generated once).
func PlaceholderPhotoBase64() string {
	photoOnce.Do(genPhoto)
	return placeholderPhoto
}

func genPhoto() {
	const w, h = 48, 60
	img := image.NewGray(image.Rect(0, 0, w, h))
	for yy := 0; yy < h; yy++ {
		for xx := 0; xx < w; xx++ {
			c := uint8(225)
			dx, dy := float64(xx-w/2), float64(yy-22)
			if dx*dx+dy*dy < 110 { // head
				c = 150
			}
			ex, ey := float64(xx-w/2)/20, float64(yy-62)/24
			if ex*ex+ey*ey < 1 { // shoulders
				c = 150
			}
			img.SetGray(xx, yy, color.Gray{Y: c})
		}
	}
	var buf bytes.Buffer
	_ = jpeg.Encode(&buf, img, &jpeg.Options{Quality: 60})
	placeholderPhoto = base64.StdEncoding.EncodeToString(buf.Bytes())
}
